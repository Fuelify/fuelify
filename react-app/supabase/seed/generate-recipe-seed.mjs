#!/usr/bin/env node
// Generates idempotent SQL for the catalog recipes in recipes.json.
//   node supabase/seed/generate-recipe-seed.mjs > supabase/seed/recipes.sql
// Each recipe is inserted only if no catalog recipe (created_by IS NULL) has the
// same title, so the output is safe to re-run after adding recipes to the JSON.
import { readFileSync } from 'node:fs';

const recipes = JSON.parse(readFileSync(new URL('./recipes.json', import.meta.url), 'utf8'));

const REQUIRED = ['title', 'description', 'cuisine', 'diet_type', 'calories', 'prep_time_minutes', 'cook_time_minutes', 'servings', 'ingredients', 'steps', 'meal_types'];
const MEAL_TYPES = new Set(['breakfast', 'lunch', 'dinner', 'snack']);
const DIETS = new Set(['Omnivore', 'Pescatarian', 'Vegetarian', 'Vegan', 'Raw', 'Other']);
const titles = new Set();
for (const r of recipes) {
  for (const k of REQUIRED) if (r[k] === undefined) throw new Error(`${r.title ?? '?'}: missing ${k}`);
  if (!DIETS.has(r.diet_type)) throw new Error(`${r.title}: unknown diet_type ${r.diet_type}`);
  if (!r.meal_types.length || r.meal_types.some((m) => !MEAL_TYPES.has(m))) throw new Error(`${r.title}: bad meal_types ${r.meal_types}`);
  if (titles.has(r.title)) throw new Error(`duplicate title: ${r.title}`);
  titles.add(r.title);
}

const str = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (v) => `${str(JSON.stringify(v))}::jsonb`;
const textArray = (v) => `ARRAY[${v.map(str).join(', ')}]::text[]`;

const values = recipes
  .map((r) => `  (${[str(r.title), str(r.description), json(r.ingredients), json(r.steps), r.prep_time_minutes, r.cook_time_minutes, r.servings, str(r.cuisine), str(r.diet_type), r.calories, textArray(r.meal_types)].join(', ')})`)
  .join(',\n');

process.stdout.write(`-- Generated by supabase/seed/generate-recipe-seed.mjs from recipes.json (${recipes.length} recipes). Do not edit by hand.
-- New titles are inserted; existing catalog recipes get their meal_types refreshed.
WITH v(title, description, ingredients, steps, prep, cook, servings, cuisine, diet, calories, meal_types) AS (VALUES
${values}
), updated AS (
  UPDATE recipes r SET meal_types = v.meal_types FROM v WHERE r.created_by IS NULL AND r.title = v.title
)
INSERT INTO recipes (title, description, ingredients, steps, prep_time_minutes, cook_time_minutes, servings, cuisine, diet_type, calories, meal_types)
SELECT v.* FROM v
WHERE NOT EXISTS (SELECT 1 FROM recipes r WHERE r.created_by IS NULL AND r.title = v.title);
`);
